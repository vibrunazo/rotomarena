"""Direct LLM Agent with Single-Call Chain-of-Thought (CoT) Reasoning."""

from __future__ import annotations

import asyncio
from typing import Any, Dict, Optional
from poke_env.battle import Battle
from poke_env.player import BattleOrder

from rotomarena.agents.base import BaseBenchmarkPlayer
from rotomarena.llm.client import LLMClient
from rotomarena.llm.prompts import format_battle_state


class DirectLLMPlayer(BaseBenchmarkPlayer):
    """
    Direct LLM Agent using single-call Chain-of-Thought reasoning
    to evaluate battle positions and select actions.
    """

    def __init__(
        self,
        player_name: str = "DirectLLMBot",
        llm_client: Optional[LLMClient] = None,
        model: Optional[str] = None,
        temperature: float = 0.2,
        battle_format: str = "gen9ou",
        team: Optional[str] = None,
        **kwargs,
    ):
        super().__init__(
            player_name=player_name,
            agent_type="direct_llm",
            battle_format=battle_format,
            team=team,
            **kwargs,
        )
        self.llm_client = llm_client or LLMClient()
        self.model = model
        self.temperature = temperature

    async def _async_choose_move(self, battle: Battle) -> BattleOrder:
        """Asynchronously queries LLM for Chain-of-Thought decision."""
        battle_state_str = format_battle_state(battle)

        try:
            decision = await self.llm_client.generate_cot_decision(
                battle_state_str=battle_state_str,
                model=self.model,
                temperature=self.temperature,
            )
        except Exception as e:
            # Fallback on API exception
            fallback_order = self.choose_default_order(battle)
            self.record_turn_telemetry(
                battle=battle,
                chosen_order=fallback_order,
                reasoning=f"LLM API Call Error: {e}. Executed fallback action.",
            )
            return fallback_order

        # Validate decision against legal actions
        chosen_order: Optional[BattleOrder] = None
        target_clean = decision.target.lower().replace("-", "").replace("_", "").replace(" ", "")

        if decision.action_type == "SWITCH" and battle.available_switches:
            for mon in battle.available_switches:
                species_clean = mon.species.lower().replace("-", "").replace("_", "").replace(" ", "")
                if target_clean in species_clean or species_clean in target_clean:
                    chosen_order = self.create_order(mon)
                    break

        elif decision.action_type == "MOVE" and battle.available_moves:
            for move in battle.available_moves:
                move_clean = move.id.lower().replace("-", "").replace("_", "").replace(" ", "")
                if target_clean in move_clean or move_clean in target_clean:
                    should_tera = decision.terastallize and battle.can_tera
                    chosen_order = self.create_order(move, terastallize=should_tera)
                    break

        # If invalid action generated by LLM, fallback gracefully
        if chosen_order is None:
            chosen_order = self.choose_default_order(battle)
            reasoning = (
                f"[FALLBACK] LLM proposed invalid action '{decision.action_type}: {decision.target}'. "
                f"Chose default valid move. \nOriginal LLM Reasoning:\n{decision.reasoning}"
            )
        else:
            reasoning = decision.reasoning

        # Record telemetry
        llm_metrics_dict = decision.metrics.model_dump() if decision.metrics else None
        self.record_turn_telemetry(
            battle=battle,
            chosen_order=chosen_order,
            reasoning=reasoning,
            llm_metrics=llm_metrics_dict,
        )

        return chosen_order
