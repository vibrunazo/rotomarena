"""Template generator for Pokémon Showdown server configuration."""

from __future__ import annotations


def generate_showdown_config(port: int = 8000, no_security: bool = True) -> str:
    """Generate a custom config.js for Pokémon Showdown with timers disabled."""
    return f"""// Pokémon Showdown configuration generated by RotomArena
'use strict';

exports.serverid = 'rotomarena';
exports.port = {port};
exports.bindaddress = '0.0.0.0';
exports.ssl = null;

// Allow unauthenticated local bot connections
exports.no_security = {str(no_security).lower()};

// Logging
exports.loglevel = 'info';
exports.consoleloglevel = 'info';

// Disable battle timers to provide sufficient time for LLM reasoning and Minimax search
exports.forcetimer = false;
exports.inactivitytimeout = 0;
exports.backuptimer = false;

// Custom formats and basic config
exports.allowcustomteams = true;
exports.report joins = false;
exports.report battles = false;
exports.report userstats = false;

// Export default options
exports.defaultbattleoptions = {{
    timer: false,
    rated: false
}};
"""
